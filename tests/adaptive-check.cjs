'use strict';
const assert = require('assert/strict');
const E = require('../adaptive-learning.js');
const R = require('../journey-rules.js');
let checks=0;
const check=(value,message)=>{assert(value,message);checks++;};
const now=Date.UTC(2026,10,12,18);
let serial=0;
const run=(node='prep:matching',wrong=[],extra={})=>({id:'session-'+(++serial),node,independent:true,completedAt:now+serial,results:Array.from({length:5},(_,i)=>({id:'q'+i,correct:!wrong.includes(i)})),...extra});
const state={runs:[run(),run()],overrides:{}};
const before=JSON.stringify(state);
check(E.progressReady(state,'prep:matching'),'two independent sessions');
check(!E.progressReady({runs:[run()]},'prep:matching'),'one session is insufficient');
check(!E.progressReady({runs:[run(),run('prep:matching',[],{independent:false})]},'prep:matching'),'supported work is not independent');
const repeated=run();
check(!E.progressReady({runs:[repeated,repeated]},'prep:matching'),'duplicate session id cannot count twice');
check(!E.progressReady({runs:[run(),run('prep:matching',[0,1,2])]},'prep:matching'),'recent failure matters');
const sameTask=()=>run('prep:matching',[],{results:Array.from({length:5},(_,i)=>({id:'alias-'+i,taskKey:'same-task',correct:true}))});
check(!E.progressReady({runs:[sameTask(),sameTask()]},'prep:matching'),'question aliases are not five tasks');
const unverified=()=>run('prep:matching',[],{evidenceVersion:2});
check(!E.progressReady({runs:[unverified(),unverified()]},'prep:matching'),'new records require explicit verification');
const scaffold=()=>run('prep:matching',[],{results:Array.from({length:5},(_,i)=>({id:'q'+i,correct:true,evidenceEligible:i<3}))});
check(!E.progressReady({runs:[scaffold(),scaffold()]},'prep:matching'),'scaffold cannot manufacture evidence');
const subskillRun=()=>run('prep:matching',[0],{results:Array.from({length:5},(_,i)=>({id:'q'+i,subskill:i===0?'kasra':'fatha',correct:i!==0}))});
check(!E.progressReady({runs:[subskillRun(),subskillRun()]},'prep:matching'),'overall score does not hide a weak subskill');
check(E.difficulty({runs:[run('x',[0,1,2])]},'x',now)==='supported','struggle reduces difficulty');
check(E.difficulty({runs:[run('x',[0,1,2]),run('x',[],{independent:false,difficulty:'supported'})]},'x',now)==='standard','supported success returns to independent practice');
check(E.difficulty({runs:[run('x'),run('x')]},'x',now)==='standard','progress alone does not certify mastery');
check(E.difficulty({runs:[run('x'),run('x')],difficulty:'supported'},'x',now)==='supported','teacher difficulty wins');
const recommendation=E.recommend(state,R,now);
check(recommendation.nodeId==='م:letter-shape','next follows prerequisites');
check(E.recommend({...state,homework:'ح:syllable-building'},R,now).nodeId==='ح:syllable-building','teacher assignment can select advanced activity');
check(E.recommend({...state,homework:'ح:syllable-building',overrides:{'ح:syllable-building':'lock'}},R,now).nodeId!=='ح:syllable-building','lock wins over assignment');
const failed={runs:[run('prep:matching',[0,1,2])],overrides:{}};
check(E.recommend(failed,R,now).reason==='targeted-review','mistakes get targeted review');
const old={runs:[run('prep:matching',[],{completedAt:now-3*86400000}),run('prep:matching',[],{completedAt:now-2*86400000})],overrides:{}};
check(E.recommend(old,R,now).reason==='spaced-review','spaced review becomes due');
check(E.recommend(old,R,now,['prep:matching']).nodeId!=='prep:matching','recently reviewed node can be excluded for a short break');
const bank=Array.from({length:8},(_,i)=>({id:'q'+i,prompt:'question '+i,answer:String(i),stimulus:'target '+i,options:[String(i),'other'],subskill:['fatha','kasra','damma'][i%3]}));
const selected=E.selectQuestions(failed,'prep:matching',bank,{seed:'fixed'});
check(selected.length===5,'short five-task sessions');
check(new Set(selected.map(q=>q.subskill)).size===3,'cover all available subskills');
check(selected.some(q=>q.id==='q0'),'include recent weak item');
check(JSON.stringify(selected)===JSON.stringify(E.selectQuestions(failed,'prep:matching',bank,{seed:'fixed'})),'seeded selection is reproducible');
const q=bank[0];check(E.taskKey(q)===E.taskKey({...q,id:'new-alias',options:[...q.options].reverse()}),'identity ignores aliases and option ordering');
check(E.selectQuestions(state,'x',[q,{...q,id:'alias'}]).length===1,'duplicate tasks are removed');
check(JSON.stringify(state)===before,'analysis never mutates records');
check(!R.nodes.filter(n=>!n.optional).some(n=>n.requires.some(id=>R.nodes.find(r=>r.id===id)?.optional)),'optional activities do not gate core progress');

const spaced={runs:[run('x',[],{mode:'assessment',completedAt:now-2*86400000}),run('x',[],{mode:'assessment',completedAt:now})]};
check(E.mastery(spaced,'x',now).status==='confirmed','mastery needs separated independent assessments');
check(E.difficulty(spaced,'x',now)==='stretch','confirmed mastery permits greater challenge');
check(E.mastery({runs:[run('x',[],{mode:'diagnostic'}),run('x',[],{mode:'practice'})]},'x',now).status!=='confirmed','diagnostic is not confirmed mastery');
check(E.planSession({runs:[run()]},R.nodes.find(n=>n.id==='م:letter-shape'),now).mode==='diagnostic','new skill can trigger a short diagnostic');
check(E.planSession({runs:[run()]},R.nodes.find(n=>n.id==='م:letter-shape'),now).count===3,'diagnostic is short');
check(E.planSession({runs:[],sessionMode:'assessment'},R.nodes[0],now).mode==='assessment','teacher chooses assessment');
check(E.recommend({runs:[run('م:letter-shape'),run('م:letter-shape')],overrides:{'prep:matching':'allow'}},R,now).reason==='varied-practice','existing games vary short learning sessions');

const A=require('../adaptive-activities.js');
for(const node of R.nodes.filter(n=>!n.optional&&n.letter))for(const q of A.questions(node)){
 check(q.options.includes(q.answer),'new task includes its answer');
 check(new Set(q.options).size===q.options.length,'new task choices are distinct');
 check(q.requiredLetters.every(l=>l===node.letter),'new task uses no future letter');
 check(q.evidenceScope==='visual-recognition','visual tasks never claim verified pronunciation');
 if(q.operation==='identify-short-mark')check(q.answer===({'َ':'الفتحة','ِ':'الكسرة','ُ':'الضمة'})[[...q.stimulus].at(-1)],'correct short mark name');
 if(q.operation==='identify-long-mark')check(q.answer===({'ا':'مد بالألف','ي':'مد بالياء','و':'مد بالواو'})[q.stimulus.at(-1)],'correct long mark name');
 if(q.operation==='build-visible-long'||q.operation==='build-visible-closed')check(q.answer===q.stimulus.split(' + ').join(''),'correct grapheme assembly');
}
check(!E.progressReady({runs:[run('x',[],{assisted:true}),run('x',[],{assisted:true})]},'x'),'assisted sessions never become independent evidence');
check(E.mastery({...spaced,criteria:{runs:3}},'x',now).status!=='confirmed','teacher requirement of three sessions is respected');

const waived=Object.fromEntries(R.nodes.filter(n=>!n.optional).map(n=>[n.id,'allow']));
const gameState={runs:[run('م:letter-shape'),run('م:letter-shape')],overrides:waived};
check(!E.recommend(gameState,R,now).nodeId?.startsWith('word-game:'),'words are not automatically assigned without taught vocabulary');
check(E.recommend({...gameState,studiedWords:['مَالْ','رَمْلْ','مَنَارْ','بَابْ','لَبَنْ']},R,now).nodeId==='word-game:1','word game uses explicitly taught vocabulary');
console.log(JSON.stringify({passed:true,checks}));
